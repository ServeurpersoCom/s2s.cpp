static bool emoji_is(uint32_t cp) {
    size_t lo = 0;
    size_t hi = sizeof(EMOJI_RANGES) / sizeof(EMOJI_RANGES[0]);
    while (lo < hi) {
        const size_t mid = (lo + hi) / 2;
        if (cp < EMOJI_RANGES[mid].first) {
            hi = mid;
        } else if (cp > EMOJI_RANGES[mid].last) {
            lo = mid + 1;
        } else {
            return true;
        }
    }
    return false;
}
